/// `namcmp(str, nam)` (cap_text.c): case-insensitive prefix match; the match
/// is rejected when the character after the name is alphanumeric or `_`.
/// Returns the pointer past the matched name.
fn namcmp<'a>(s: &'a str, name: &str) -> Option<&'a str> {
    let mut chars = s.chars();
    for n in name.chars() {
        let c = chars.next()?;
        if c.to_ascii_lowercase() != n {
            return None;
        }
    }
    if let Some(next) = chars.clone().next() {
        if next.is_alphanumeric() || next == '_' {
            return None;
        }
    }
    Some(&s[name.len()..])
}

/// `lookupname` (cap_text.c): numeric (strtoul base 0 — hex `0x` accepted,
/// CAP-NAME-0004) or named (the `cap_`-prefixed `_cap_names`, matched
/// case-insensitively on the prefix; CAP-NAME-0001..0003).  The returned
/// string advances past the token (the numeric advance works through the
/// union aliasing of `str.constp`/`str.p` in the C — archived in
/// CAP-NAME-0005).
fn lookupname(s: &str) -> Option<(i32, &str)> {
    let first = s.chars().next()?;
    if first.is_ascii_digit() {
        // strtoul(s, &end, 0)
        let end = s
            .find(|c: char| {
                !(c.is_ascii_digit()
                    || c == 'x'
                    || c == 'X'
                    || ('a'..='f').contains(&c.to_ascii_lowercase())
                    || c == '0')
            })
            .unwrap_or(s.len());
        let (numstr, rest) = s.split_at(end);
        // re-validate: strtoul base 0 accepts decimal and 0x hex
        let n = if let Some(hex) = numstr
            .strip_prefix("0x")
            .or_else(|| numstr.strip_prefix("0X"))
        {
            u64::from_str_radix(hex, 16).ok()?
        } else {
            numstr.parse::<u64>().ok()?
        };
        if n >= CAP_MAX_BITS as u64 {
            return None;
        }
        // note: for "0x2" strtoul stops after "2"; for "5=ep" after "5"
        return Some((n as i32, rest));
    }
    for (idx, name) in CAP_NAMES.iter().enumerate() {
        if let Some(rest) = namcmp(s, name) {
            return Some((idx as i32, rest));
        }
    }
    None
}

/// `cap_from_name(name, &value)` (CAP-NAME-0006): returns Ok(value) when the
/// name parses; the C returns 0/-1.
pub fn cap_from_name(name: &str) -> CapResult<i32> {
    match lookupname(name) {
        Some((n, _)) => Ok(n),
        None => Err(CapErrno::EINVAL),
    }
}

/// `cap_to_name(cap)` (CAP-NAME-0007): the `cap_`-prefixed name for named
/// capabilities, otherwise the decimal rendering (`%u` of the value).
#[must_use]
pub fn cap_to_name(cap: i32) -> String {
    if (0..CAP_BITS as i32).contains(&cap) {
        CAP_NAMES[cap as usize].to_string()
    } else {
        // asprintf("%u", (unsigned)cap) — the C passes an int through %u.
        format!("{}", cap as u32)
    }
}

