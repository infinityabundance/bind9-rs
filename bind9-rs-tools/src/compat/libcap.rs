/// `cap_size(cap_d)` (CAP-EXT-0001): the portable-format size in bytes.
#[must_use]
pub fn cap_size(caps: &CapState) -> usize {
    // _cap_size_locked: highest nonzero combined word, byte-rounded.
    let mut used = 0usize;
    for (j, _) in (0..8usize).step_by(4).enumerate() {
        let val = caps.eff[j / 4] | caps.perm[j / 4] | caps.inh[j / 4];
        if val == 0 {
            continue;
        }
        used = if val > 0x0000_ffff {
            if val > 0x00ff_ffff {
                j + 4
            } else {
                j + 3
            }
        } else if val > 0x0000_00ff {
            j + 2
        } else {
            j + 1
        };
    }
    if used < 8 {
        used = 8;
    }
    4 + 1 + 3 * used
}

/// `cap_copy_ext(ext, cap_d, length)` (CAP-EXT-0002): serialize into the
/// portable format; the destination must be at least `cap_size` bytes.
pub fn cap_copy_ext(dest: &mut [u8], caps: &CapState) -> CapResult<usize> {
    let csz = cap_size(caps);
    if dest.len() < csz {
        return Err(CapErrno::EINVAL);
    }
    let len_set = (csz - 5) / 3;
    dest[0..4].copy_from_slice(&CAP_EXT_MAGIC);
    dest[4] = len_set as u8;
    for (i, set) in [CapFlag::Effective, CapFlag::Permitted, CapFlag::Inheritable]
        .iter()
        .enumerate()
    {
        let mut j = 0usize;
        while j < len_set {
            // each u32 (byte offset j..j+4) comes from flat[set][j/4]
            let mut v = caps.flat(*set, j / 4);
            for k in 0..4 {
                if j + k < len_set {
                    dest[5 + (j + k) * 3 + i] = (v & 0xff) as u8;
                    v >>= 8;
                }
            }
            j += 4;
        }
    }
    Ok(csz)
}

/// `cap_copy_int(ext)` (CAP-EXT-0003): import the portable format (magic +
/// valid structure assumed, as the C does).
pub fn cap_copy_int(ext: &[u8]) -> CapResult<CapState> {
    if ext.len() < 5 || ext[0..4] != CAP_EXT_MAGIC {
        return Err(CapErrno::EINVAL);
    }
    let mut caps = CapState::empty();
    let blen = ext[4] as usize;
    for (i, set) in [CapFlag::Effective, CapFlag::Permitted, CapFlag::Inheritable]
        .iter()
        .enumerate()
    {
        let mut bno = 0usize;
        for blk in 0..2usize {
            // at most 4 bytes per u32, each guarded by bno != blen (the C
            // reads exactly 4 per block; the guard skips beyond blen).
            let mut val = 0u32;
            let mut shift = 0;
            for _ in 0..4 {
                if bno < blen {
                    let byte = *ext.get(5 + bno * 3 + i).unwrap_or(&0);
                    val |= (byte as u32) << shift;
                    bno += 1;
                }
                shift += 8;
            }
            caps.set_flat(*set, blk, val);
        }
    }
    Ok(caps)
}

/// `cap_copy_int_check(ext, length)` (CAP-EXT-0004): validate the length
/// against the declared set length before importing.
pub fn cap_copy_int_check(ext: &[u8]) -> CapResult<CapState> {
    if ext.len() < 5 {
        return Err(CapErrno::EINVAL);
    }
    let needed = 5 + ext[4] as usize * 3;
    if ext.len() < needed {
        return Err(CapErrno::EINVAL);
    }
    cap_copy_int(ext)
}

