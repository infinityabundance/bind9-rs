fn is_name_char(c: char) -> bool {
    c.is_alphanumeric() || c == '_'
}

/// `cap_from_text(str)` (cap_text.c, CAP-TEXT-0001..0008): a faithful
/// transcription of the clause parser.
pub fn cap_from_text(text: &str) -> CapResult<CapState> {
    let mut res = CapState::empty();
    let mut s = text;

    loop {
        // skip leading spaces
        while let Some(c) = s.chars().next() {
            if c.is_whitespace() {
                s = &s[1..];
            } else {
                break;
            }
        }
        if s.is_empty() {
            return Ok(res);
        }

        let mut list = [0u32; 2];
        let mut listed = false;

        let first = s.chars().next().unwrap();
        if is_name_char(first) {
            loop {
                if let Some(rest) = namcmp(s, "all") {
                    s = rest;
                    forceall(&mut list, u32::MAX);
                } else {
                    let (n, rest) = match lookupname(s) {
                        Some(v) => v,
                        None => return Err(CapErrno::EINVAL),
                    };
                    s = rest;
                    list[(n as usize) >> 5] |= 1u32 << ((n as usize) & 31);
                }
                if !s.starts_with(',') {
                    break;
                }
                let after = &s[1..];
                if after.chars().next().map_or(true, |c| !is_name_char(c)) {
                    return Err(CapErrno::EINVAL);
                }
                s = after;
            }
            listed = true;
        } else if first == '+' || first == '-' {
            // "require a list of capabilities"
            return Err(CapErrno::EINVAL);
        } else {
            forceall(&mut list, u32::MAX);
        }

        // identify first operation
        let mut op = s.chars().next().unwrap();
        s = &s[1..];
        if op == '=' && s.starts_with('+') || (op == '=' && s.starts_with('-')) {
            if !listed {
                return Err(CapErrno::EINVAL);
            }
            op = if s.starts_with('+') { 'P' } else { 'M' }; // skip '='
            s = &s[1..];
        } else if op != '+' && op != '-' && op != '=' {
            return Err(CapErrno::EINVAL);
        }

        // cycle through list of actions; `flags` accumulates across flag
        // characters (cap_text.c declares it in the clause loop and resets it
        // only on a new +/- directive — CAP-TEXT-0003).
        let mut flags = 0i32;
        loop {
            let mut c = s.chars().next();
            match c {
                Some(ch) if !ch.is_whitespace() => {
                    match ch {
                        'e' => flags |= LIBCAP_EFF,
                        'i' => flags |= LIBCAP_INH,
                        'p' => flags |= LIBCAP_PER,
                        _ => return Err(CapErrno::EINVAL),
                    }
                    s = &s[1..];
                }
                // only '=' may be followed by whitespace or end-of-string
                // (cap_text.c: `else if (op != '=') goto bad;`)
                _ if op != '=' => return Err(CapErrno::EINVAL),
                _ => {}
            }

            match op {
                '=' | 'P' | 'M' => {
                    for b in 0..2 {
                        res.eff[b] &= !list[b];
                        res.perm[b] &= !list[b];
                        res.inh[b] &= !list[b];
                    }
                    if op != 'M' {
                        if flags & LIBCAP_EFF != 0 {
                            for b in 0..2 {
                                res.eff[b] |= list[b];
                            }
                        }
                        if flags & LIBCAP_PER != 0 {
                            for b in 0..2 {
                                res.perm[b] |= list[b];
                            }
                        }
                        if flags & LIBCAP_INH != 0 {
                            for b in 0..2 {
                                res.inh[b] |= list[b];
                            }
                        }
                    }
                }
                '+' => {
                    if flags & LIBCAP_EFF != 0 {
                        for b in 0..2 {
                            res.eff[b] |= list[b];
                        }
                    }
                    if flags & LIBCAP_PER != 0 {
                        for b in 0..2 {
                            res.perm[b] |= list[b];
                        }
                    }
                    if flags & LIBCAP_INH != 0 {
                        for b in 0..2 {
                            res.inh[b] |= list[b];
                        }
                    }
                }
                '-' => {
                    if flags & LIBCAP_EFF != 0 {
                        for b in 0..2 {
                            res.eff[b] &= !list[b];
                        }
                    }
                    if flags & LIBCAP_PER != 0 {
                        for b in 0..2 {
                            res.perm[b] &= !list[b];
                        }
                    }
                    if flags & LIBCAP_INH != 0 {
                        for b in 0..2 {
                            res.inh[b] &= !list[b];
                        }
                    }
                }
                _ => unreachable!(),
            }

            // new directive?
            if s.starts_with('+') || s.starts_with('-') {
                if !listed {
                    return Err(CapErrno::EINVAL);
                }
                flags = 0; // reset the flags (cap_text.c)
                op = s.chars().next().unwrap();
                s = &s[1..];
                if s.chars().next().map_or(true, |c| !c.is_alphabetic()) {
                    return Err(CapErrno::EINVAL);
                }
            } else if c.is_none() || s.chars().next().map_or(true, |c| c.is_whitespace()) {
                // end of this clause; the loop continues at the top-level
                // where whitespace is skipped and an empty string returns.
                break;
            }
        }
    }
}

/// `forceall` (cap_text.c): assign `value` to every named capability bit
/// (masked to `cap_max_bits()`), zero otherwise.
fn forceall(flat: &mut [u32; 2], value: u32) {
    let cmb = cap_max_bits();
    for (n, f) in flat.iter_mut().enumerate() {
        let base = 32 * n;
        let mask = if cmb >= base + 32 {
            u32::MAX
        } else if cmb > base {
            (1u64 << (cmb % 32)) as u32 - 1
        } else {
            0
        };
        *f = value & mask;
    }
}

fn getstateflags(caps: &CapState, capno: i32) -> i32 {
    let mut f = 0;
    if caps.isset(CapFlag::Effective, capno) {
        f |= LIBCAP_EFF;
    }
    if caps.isset(CapFlag::Permitted, capno) {
        f |= LIBCAP_PER;
    }
    if caps.isset(CapFlag::Inheritable, capno) {
        f |= LIBCAP_INH;
    }
    f
}

/// `cap_to_text(caps)` (cap_text.c, CAP-TEXT-0009..0012): the canonical text
/// form.  Returns (text, length) where length is `p - base` (after the "= "
/// merge).
#[must_use]
pub fn cap_to_text(caps: &CapState) -> (String, usize) {
    let cmb = cap_max_bits();
    let mut histo = [0usize; 8];
    for n in 0..cmb {
        histo[getstateflags(caps, n as i32) as usize] += 1;
    }
    // prevailing state: the most common combination, biased to 0.
    let mut m = 7usize;
    for t in (0..7).rev() {
        if histo[t] >= histo[m] {
            m = t;
        }
    }

    let mut buf = String::new();
    buf.push('=');
    if m & LIBCAP_EFF as usize != 0 {
        buf.push('e');
    }
    if m & LIBCAP_INH as usize != 0 {
        buf.push('i');
    }
    if m & LIBCAP_PER as usize != 0 {
        buf.push('p');
    }
    let mut base = 0usize; // index into buf where the returned text starts

    for t in (0..8).rev() {
        if t == m || histo[t] == 0 {
            continue;
        }
        buf.push(' ');
        for n in 0..cmb {
            if getstateflags(caps, n as i32) as usize == t {
                buf.push_str(&cap_to_name(n as i32));
                buf.push(',');
            }
        }
        buf.pop(); // remove trailing comma
        let add = t as i32 & !(m as i32);
        if add != 0 {
            let mut op = '+';
            if buf.as_bytes().get(base).copied() == Some(b'=')
                && buf.as_bytes().get(base + 1).copied() == Some(b' ')
            {
                // "= foo,...+eip ..." → "foo,...=eip ..." (equivalent, shorter)
                base += 2;
                op = '=';
            }
            buf.push(op);
            if add & LIBCAP_EFF != 0 {
                buf.push('e');
            }
            if add & LIBCAP_INH != 0 {
                buf.push('i');
            }
            if add & LIBCAP_PER != 0 {
                buf.push('p');
            }
        }
        let rem = !(t as i32) & m as i32;
        if rem != 0 {
            buf.push('-');
            if rem & LIBCAP_EFF != 0 {
                buf.push('e');
            }
            if rem & LIBCAP_INH != 0 {
                buf.push('i');
            }
            if rem & LIBCAP_PER != 0 {
                buf.push('p');
            }
        }
    }

    // remaining unnamed bits (cmb..64) — all must be +
    let mut histo2 = [0usize; 8];
    for n in cmb..CAP_MAX_BITS {
        histo2[getstateflags(caps, n as i32) as usize] += 1;
    }
    for t in (2..8).rev() {
        if histo2[t] == 0 {
            continue;
        }
        buf.push(' ');
        for n in cmb..CAP_MAX_BITS {
            if getstateflags(caps, n as i32) as usize == t {
                buf.push_str(&cap_to_name(n as i32));
                buf.push(',');
            }
        }
        buf.pop();
        buf.push('+');
        if t & LIBCAP_EFF as usize != 0 {
            buf.push('e');
        }
        if t & LIBCAP_INH as usize != 0 {
            buf.push('i');
        }
        if t & LIBCAP_PER as usize != 0 {
            buf.push('p');
        }
    }

    let len = buf.len() - base;
    (buf[base..].to_string(), len)
}

