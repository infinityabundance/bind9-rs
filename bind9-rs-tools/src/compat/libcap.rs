/// The internal capability state (`struct _cap_struct`: three flat sets over
/// `__CAP_BLKS` 32-bit words + `rootid`).  `flat[set]` layout per block is
/// effective/permitted/inheritable (kernel `__user_cap_data_struct`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CapState {
    /// Effective set, two 32-bit words.
    pub eff: [u32; 2],
    /// Permitted set, two 32-bit words.
    pub perm: [u32; 2],
    /// Inheritable set, two 32-bit words.
    pub inh: [u32; 2],
    /// The user-namespace root owner (`cap_d->rootid`, v3 only).
    pub rootid: u32,
}

impl Default for CapState {
    fn default() -> Self {
        Self::empty()
    }
}

impl CapState {
    /// `cap_init()`: a blank set with the v3 header (CAP-ALLOC-0002).
    #[must_use]
    pub fn empty() -> Self {
        CapState {
            eff: [0, 0],
            perm: [0, 0],
            inh: [0, 0],
            rootid: 0,
        }
    }

    /// `cap_dup()` (CAP-ALLOC-0003): a deep copy.
    #[must_use]
    pub fn dup(&self) -> Self {
        self.clone()
    }

    fn block_of(value: i32) -> usize {
        (value as usize) >> 5
    }

    fn mask_of(value: i32) -> u32 {
        1u32 << ((value as usize) & 31)
    }

    fn set(&mut self, set: CapFlag, value: i32) {
        let b = Self::block_of(value);
        match set {
            CapFlag::Effective => self.eff[b] |= Self::mask_of(value),
            CapFlag::Permitted => self.perm[b] |= Self::mask_of(value),
            CapFlag::Inheritable => self.inh[b] |= Self::mask_of(value),
        }
    }

    fn lower(&mut self, set: CapFlag, value: i32) {
        let b = Self::block_of(value);
        let m = !Self::mask_of(value);
        match set {
            CapFlag::Effective => self.eff[b] &= m,
            CapFlag::Permitted => self.perm[b] &= m,
            CapFlag::Inheritable => self.inh[b] &= m,
        }
    }

    fn isset(&self, set: CapFlag, value: i32) -> bool {
        let b = Self::block_of(value);
        let m = Self::mask_of(value);
        match set {
            CapFlag::Effective => self.eff[b] & m != 0,
            CapFlag::Permitted => self.perm[b] & m != 0,
            CapFlag::Inheritable => self.inh[b] & m != 0,
        }
    }

    fn flat(&self, set: CapFlag, block: usize) -> u32 {
        match set {
            CapFlag::Effective => self.eff[block],
            CapFlag::Permitted => self.perm[block],
            CapFlag::Inheritable => self.inh[block],
        }
    }

    fn set_flat(&mut self, set: CapFlag, block: usize, v: u32) {
        match set {
            CapFlag::Effective => self.eff[block] = v,
            CapFlag::Permitted => self.perm[block] = v,
            CapFlag::Inheritable => self.inh[block] = v,
        }
    }

    /// `cap_clear()` (CAP-FLAG-0001): zero every set.
    pub fn clear(&mut self) {
        self.eff = [0, 0];
        self.perm = [0, 0];
        self.inh = [0, 0];
    }

    /// `cap_clear_flag()` (CAP-FLAG-0002): zero one set.
    pub fn clear_flag(&mut self, flag: CapFlag) {
        for b in 0..2 {
            self.set_flat(flag, b, 0);
        }
    }

    /// `cap_get_flag()` (CAP-FLAG-0003).  Out-of-range values are EINVAL.
    pub fn get_flag(&self, value: i32, set: CapFlag) -> CapResult<CapFlagValue> {
        if value < 0 || value >= CAP_MAX_BITS as i32 {
            return Err(CapErrno::EINVAL);
        }
        Ok(if self.isset(set, value) {
            CapFlagValue::Set
        } else {
            CapFlagValue::Clear
        })
    }

    /// `cap_set_flag()` (CAP-FLAG-0004).  Per libcap, out-of-range entries in
    /// the array are *skipped* with no error; an empty or over-long array or
    /// a bad set/raise value is EINVAL (CAP-FLAG-0005).
    pub fn set_flag(&mut self, set: CapFlag, values: &[i32], raise: CapFlagValue) -> CapResult<()> {
        if values.is_empty() || values.len() >= CAP_MAX_BITS {
            return Err(CapErrno::EINVAL);
        }
        match set {
            CapFlag::Effective | CapFlag::Permitted | CapFlag::Inheritable => {}
        }
        match raise {
            CapFlagValue::Set | CapFlagValue::Clear => {}
        }
        for &v in values {
            if v < 0 || v >= CAP_MAX_BITS as i32 {
                // libcap: "weird capability - skipped"
                continue;
            }
            if raise == CapFlagValue::Set {
                self.set(set, v);
            } else {
                self.lower(set, v);
            }
        }
        Ok(())
    }

    /// `cap_fill_flag(cap_d, to, ref, from)` (CAP-FLAG-0006): copy one set of
    /// `ref` into `to` of self.
    pub fn fill_flag(&mut self, to: CapFlag, reference: &CapState, from: CapFlag) -> CapResult<()> {
        for b in 0..2 {
            let v = reference.flat(from, b);
            self.set_flat(to, b, v);
        }
        Ok(())
    }

    /// `cap_fill(cap_d, to, from)` (CAP-FLAG-0007): copy one set to another
    /// within the same state.
    pub fn fill(&mut self, to: CapFlag, from: CapFlag) -> CapResult<()> {
        let snapshot = self.dup();
        self.fill_flag(to, &snapshot, from)
    }

    /// `cap_compare(a, b)` (CAP-FLAG-0008): returns a bitmask of
    /// `LIBCAP_EFF | LIBCAP_INH | LIBCAP_PER` for the sets that differ.
    pub fn compare(&self, other: &CapState) -> i32 {
        let mut result = 0;
        for b in 0..2 {
            if self.eff[b] != other.eff[b] {
                result |= LIBCAP_EFF;
            }
            if self.inh[b] != other.inh[b] {
                result |= LIBCAP_INH;
            }
            if self.perm[b] != other.perm[b] {
                result |= LIBCAP_PER;
            }
        }
        result
    }
}

