/// The IAB tuple (`cap_iab_s`): inheritable, ambient, and "drop from
/// bounding" vectors (CAP-IAB-0001).
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct CapIab {
    pub i: [u32; 2],
    pub a: [u32; 2],
    pub nb: [u32; 2],
}

impl CapIab {
    /// `cap_iab_init()`.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// `cap_iab_get_vector` (CAP-IAB-0002): 0 when out of range.
    #[must_use]
    pub fn get_vector(&self, vec: CapIabVector, bit: i32) -> CapFlagValue {
        if bit < 0 || bit as usize >= cap_max_bits() {
            return CapFlagValue::Clear;
        }
        let o = (bit as usize) >> 5;
        let mask = 1u32 << (bit & 31);
        let v = match vec {
            CapIabVector::Inh => self.i[o] & mask,
            CapIabVector::Amb => self.a[o] & mask,
            CapIabVector::Bound => self.nb[o] & mask,
        };
        if v != 0 {
            CapFlagValue::Set
        } else {
            CapFlagValue::Clear
        }
    }

    /// `cap_iab_set_vector` (CAP-IAB-0003): setting A implies I; lowering I
    /// lowers A; B is independent.
    pub fn set_vector(
        &mut self,
        vec: CapIabVector,
        bit: i32,
        raised: CapFlagValue,
    ) -> CapResult<()> {
        if bit < 0 || bit as usize >= cap_max_bits() {
            return Err(CapErrno::EINVAL);
        }
        if !matches!(raised, CapFlagValue::Set | CapFlagValue::Clear) {
            return Err(CapErrno::EINVAL);
        }
        let o = (bit as usize) >> 5;
        let on = 1u32 << (bit & 31);
        let mask = !on;
        match vec {
            CapIabVector::Inh => {
                self.i[o] = (self.i[o] & mask) | if raised == CapFlagValue::Set { on } else { 0 };
                self.a[o] &= self.i[o];
            }
            CapIabVector::Amb => {
                self.a[o] = (self.a[o] & mask) | if raised == CapFlagValue::Set { on } else { 0 };
                self.i[o] |= self.a[o];
            }
            CapIabVector::Bound => {
                self.nb[o] = (self.nb[o] & mask) | if raised == CapFlagValue::Set { on } else { 0 };
            }
        }
        Ok(())
    }

    /// `cap_iab_fill` (CAP-IAB-0004): copy a cap_t flag vector into an IAB
    /// vector (bounding bits are inverted — "to be dropped").
    pub fn fill(&mut self, vec: CapIabVector, caps: &CapState, flag: CapFlag) -> CapResult<()> {
        for i in 0..2 {
            match vec {
                CapIabVector::Inh => {
                    self.i[i] = caps.flat(flag, i);
                    self.a[i] &= self.i[i];
                }
                CapIabVector::Amb => {
                    self.a[i] = caps.flat(flag, i);
                    self.i[i] |= caps.flat(flag, i);
                }
                CapIabVector::Bound => {
                    self.nb[i] = !caps.flat(flag, i);
                }
            }
        }
        Ok(())
    }

    /// `cap_iab_compare` (CAP-IAB-0005): bitmask of `1 << vector` for each
    /// differing vector.
    #[must_use]
    pub fn compare(&self, other: &CapIab) -> i32 {
        let mut result = 0;
        for j in 0..2 {
            if self.i[j] != other.i[j] {
                result |= 1 << (CapIabVector::Inh as i32);
            }
            if self.a[j] != other.a[j] {
                result |= 1 << (CapIabVector::Amb as i32);
            }
            if self.nb[j] != other.nb[j] {
                result |= 1 << (CapIabVector::Bound as i32);
            }
        }
        result
    }
}

/// `cap_iab_to_text` (cap_text.c, CAP-IAB-0006): `,`-separated `!`/`^`/`%`
/// prefixed names.
#[must_use]
pub fn cap_iab_to_text(iab: &CapIab) -> String {
    let cmb = cap_max_bits();
    let mut out = String::new();
    let mut first = true;
    for c in 0..cmb {
        let o = c >> 5;
        let bit = 1u32 << (c & 31);
        let ib = iab.i[o] & bit;
        let ab = iab.a[o] & bit;
        let nbb = iab.nb[o] & bit;
        if nbb | ab | ib == 0 {
            continue;
        }
        if !first {
            out.push(',');
        }
        let mut keep = false;
        if nbb != 0 {
            out.push('!');
            keep = true;
        }
        if ab != 0 {
            out.push('^');
            keep = true;
        } else if nbb != 0 && ib != 0 {
            out.push('%');
        }
        if keep || ib != 0 {
            out.push_str(&cap_to_name(c as i32));
            first = false;
        }
    }
    out
}

/// `cap_iab_from_text` (cap_text.c, CAP-IAB-0007): prefixes `!` (bound
/// drop), `^` (ambient + inheritable), `%` (inheritable only); a bare name
/// means inheritable; entries are `,`-separated with no whitespace.
pub fn cap_iab_from_text(text: &str) -> CapResult<CapIab> {
    let mut iab = CapIab::new();
    let mut s = text;
    let mut flags = 0u32;
    loop {
        let mut consumed_prefix = false;
        while let Some(ch) = s.chars().next() {
            match ch {
                '!' => flags |= 1u32 << CapIabVector::Bound as i32,
                '^' => {
                    flags |= (1u32 << CapIabVector::Inh as i32) | (1u32 << CapIabVector::Amb as i32)
                }
                '%' => flags |= 1u32 << CapIabVector::Inh as i32,
                _ => break,
            }
            s = &s[1..];
            consumed_prefix = true;
        }
        if s.is_empty() {
            return Ok(iab);
        }
        if flags == 0 && !consumed_prefix {
            flags = 1u32 << CapIabVector::Inh as i32;
        }
        let (c, rest) = match lookupname(s) {
            Some(v) => v,
            None => return Err(CapErrno::EINVAL),
        };
        s = rest;
        let o = (c as usize) >> 5;
        let mask = 1u32 << (c & 31);
        if flags & (1u32 << CapIabVector::Inh as i32) != 0 {
            iab.i[o] |= mask;
        }
        if flags & (1u32 << CapIabVector::Amb as i32) != 0 {
            iab.a[o] |= mask;
        }
        if flags & (1u32 << CapIabVector::Bound as i32) != 0 {
            iab.nb[o] |= mask;
        }
        if s.is_empty() {
            return Ok(iab);
        }
        if !s.starts_with(',') {
            return Err(CapErrno::EINVAL);
        }
        s = &s[1..];
        flags = 0;
    }
}

