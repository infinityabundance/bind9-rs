use std::sync::OnceLock;

/// `cap_max_bits()`: the first unnamed capability (kernel `cap_last_cap` +
/// 1).  libcap probes it at startup (binary search over `cap_get_bound`,
/// falling back to `__CAP_BITS`); we read `/proc/sys/kernel/cap_last_cap`
/// with the same fallback (CAP-PROC-0004).
#[must_use]
pub fn cap_max_bits() -> usize {
    static MAX_BITS: OnceLock<usize> = OnceLock::new();
    *MAX_BITS.get_or_init(|| {
        if let Ok(v) = std::fs::read_to_string("/proc/sys/kernel/cap_last_cap") {
            if let Ok(n) = v.trim().parse::<usize>() {
                return n + 1;
            }
        }
        CAP_BITS
    })
}

