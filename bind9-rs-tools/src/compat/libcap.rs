/// A `cap_launch_t` equivalent: the attributes of a `cap_launch` invocation.
#[derive(Debug, Clone, Default)]
pub struct CapLauncher {
    pub uid: Option<u32>,
    pub gid: Option<u32>,
    pub groups: Option<Vec<u32>>,
    pub mode: Option<CapMode>,
    pub iab: Option<CapIab>,
    pub chroot: Option<String>,
}

/// `cap_launch(attr, argv, envp)` (CAP-LAUNCH-0012): fork, apply the
/// attribute changes in the child, execve; report child setup failures via
/// the pipe.  Returns the child pid (the caller waitpids).
pub fn cap_launch(
    attr: &CapLauncher,
    arg0: &str,
    argv: &[String],
    envp: &[String],
) -> CapResult<i32> {
    let (ps_r, ps_w) = lx::pipe2(libc::O_CLOEXEC).map_err(CapErrno)?;
    let child = lx::fork().map_err(CapErrno)?;
    if child == 0 {
        // child
        lx::close(ps_r);
        let _ = lx::prctl(PR_SET_NAME as i32, 0, 0, 0, 0, 0);
        let result = child_setup(attr, arg0, argv, envp);
        let errno = match result {
            Ok(()) => 0,
            Err(e) => e.0,
        };
        // communicate errno to the parent
        let bytes = errno.to_ne_bytes();
        let _ = lx::write_fd(ps_w, &bytes);
        lx::close(ps_w);
        std::process::exit(1);
    }
    lx::close(ps_w);
    if child < 0 {
        lx::close(ps_r);
        return Err(CapErrno(
            std::io::Error::last_os_error().raw_os_error().unwrap_or(0),
        ));
    }
    // parent: wait for the child's setup report
    let mut buf = [0u8; 4];
    match lx::read_fd(ps_r, &mut buf) {
        Ok(0) => {
            // exec succeeded (child is gone or running)
            lx::close(ps_r);
            Ok(child)
        }
        Ok(_) => {
            let e = i32::from_ne_bytes(buf);
            let _ = lx::waitpid(child);
            lx::close(ps_r);
            Err(CapErrno(e))
        }
        Err(_) => {
            lx::close(ps_r);
            Ok(child)
        }
    }
}

fn child_setup(attr: &CapLauncher, arg0: &str, argv: &[String], envp: &[String]) -> CapResult<()> {
    if let Some(uid) = attr.uid {
        cap_setuid(uid)?;
    }
    if let Some(gid) = attr.gid {
        match &attr.groups {
            Some(g) => cap_setgroups(gid, g)?,
            None => cap_setgroups(gid, &[])?,
        }
    }
    if let Some(mode) = attr.mode {
        cap_set_mode(mode)?;
    }
    if let Some(iab) = &attr.iab {
        cap_iab_set_proc(iab)?;
    }
    if let Some(root) = &attr.chroot {
        let c = CString::new(root.as_str()).map_err(|_| CapErrno::EINVAL)?;
        lx::chroot(&c).map_err(CapErrno)?;
        lx::chdir_root().map_err(CapErrno)?;
    }
    let c_arg0 = CString::new(arg0).map_err(|_| CapErrno::EINVAL)?;
    let c_argv: Vec<CString> = argv
        .iter()
        .map(|a| CString::new(a.as_str()))
        .collect::<Result<_, _>>()
        .map_err(|_| CapErrno::EINVAL)?;
    let c_envp: Vec<CString> = envp
        .iter()
        .map(|a| CString::new(a.as_str()))
        .collect::<Result<_, _>>()
        .map_err(|_| CapErrno::EINVAL)?;
    lx::execve(&c_arg0, &c_argv, &c_envp).map_err(CapErrno)
}

