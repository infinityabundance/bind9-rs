/// `cap_mode_name(flavor)` (CAP-PROC-0015).
#[must_use]
pub fn cap_mode_name(flavor: CapMode) -> &'static str {
    match flavor {
        CapMode::NoPriv => "NOPRIV",
        CapMode::Pure1eInit => "PURE1E_INIT",
        CapMode::Pure1e => "PURE1E",
        CapMode::Uncertain => "UNCERTAIN",
        CapMode::Hybrid => "HYBRID",
        _ => "UNKNOWN",
    }
}

/// `cap_get_mode()` (CAP-PROC-0016): the mode inferred from secbits,
/// ambient, capability state and bounding set.
pub fn cap_get_mode() -> CapMode {
    let secbits = cap_get_secbits().unwrap_or(0);
    if secbits == 0 {
        return CapMode::Hybrid;
    }
    if secbits & CAP_SECURED_BITS_BASIC != CAP_SECURED_BITS_BASIC {
        return CapMode::Uncertain;
    }
    // validate ambient is not set
    let mut c = 0i32;
    loop {
        match cap_get_ambient(c) {
            Ok(0) => c += 1,
            Ok(_) => return CapMode::Uncertain,
            Err(_) => {
                if c != 0 && secbits != CAP_SECURED_BITS_AMBIENT {
                    return CapMode::Uncertain;
                }
                break;
            }
        }
    }
    // compare working vs empty
    let working = cap_get_proc().unwrap_or_default();
    let empty = CapState::empty();
    let cf = empty.compare(&working);
    if cf & LIBCAP_INH != 0 {
        return CapMode::Pure1e;
    }
    if cf & LIBCAP_PER != 0 || cf & LIBCAP_EFF != 0 {
        return CapMode::Pure1eInit;
    }
    let mut c = 0i32;
    loop {
        match cap_get_bound(c) {
            Ok(0) => c += 1,
            Ok(_) => return CapMode::Pure1eInit,
            Err(_) => break,
        }
    }
    CapMode::NoPriv
}

/// `cap_set_mode(flavor)` (CAP-PROC-0017): a faithful transcription of
/// `_cap_set_mode` (including the side effect of clearing CAP_EFFECTIVE at
/// the end, whether or not the mode change succeeded).
pub fn cap_set_mode(flavor: CapMode) -> CapResult<()> {
    let mut secbits = CAP_SECURED_BITS_AMBIENT;
    let mut working = cap_get_proc()?;
    let raise_setpcap = [cap::SETPCAP];
    let mut ret = working
        .set_flag(CapFlag::Effective, &raise_setpcap, CapFlagValue::Set)
        .and_then(|_| cap_set_proc(&working));
    if ret.is_ok() {
        match flavor {
            CapMode::NoPriv | CapMode::Pure1eInit => {
                working.clear_flag(CapFlag::Inheritable);
            }
            _ => {}
        }
        match flavor {
            CapMode::NoPriv | CapMode::Pure1e | CapMode::Pure1eInit => {
                if cap_get_ambient(cap::CHOWN).is_err() {
                    secbits = CAP_SECURED_BITS_BASIC;
                } else {
                    ret = cap_reset_ambient();
                }
                if ret.is_ok() {
                    ret = cap_set_secbits(secbits);
                }
                if flavor == CapMode::NoPriv {
                    let mut c = 0i32;
                    while cap_get_bound(c).is_ok() {
                        let _ = cap_drop_bound(c);
                        c += 1;
                    }
                    working.clear_flag(CapFlag::Permitted);
                    let _ = lx::prctl(PR_SET_NO_NEW_PRIVS as i32, 1, 0, 0, 0, 0);
                }
            }
            CapMode::Hybrid => {
                ret = cap_set_secbits(0);
            }
            CapMode::Uncertain => {
                return Err(CapErrno::EINVAL);
            }
        }
    }
    working.clear_flag(CapFlag::Effective);
    let _ = cap_set_proc(&working);
    ret
}

/// `cap_setuid(uid)` (CAP-PROC-0018): raise CAP_SETUID effective, KEEPCAPS
/// on, setuid, KEEPCAPS off, clear effective (side effect).
pub fn cap_setuid(uid: u32) -> CapResult<()> {
    let raise = [cap::SETUID];
    let mut working = cap_get_proc()?;
    working.set_flag(CapFlag::Effective, &raise, CapFlagValue::Set)?;
    let _ = lx::prctl(PR_SET_KEEPCAPS as i32, 1, 0, 0, 0, 0);
    let ret = cap_set_proc(&working).and_then(|_| lx::setuid(uid).map_err(CapErrno));
    let olderrno = ret.as_ref().err().copied();
    let _ = lx::prctl(PR_SET_KEEPCAPS as i32, 0, 0, 0, 0, 0);
    working.clear_flag(CapFlag::Effective);
    let _ = cap_set_proc(&working);
    match olderrno {
        Some(e) => Err(e),
        None => ret,
    }
}

/// `cap_setgroups(gid, groups)` (CAP-PROC-0019): raise CAP_SETGID effective,
/// setgid + setgroups, clear effective (side effect).
pub fn cap_setgroups(gid: u32, groups: &[u32]) -> CapResult<()> {
    let raise = [cap::SETGID];
    let mut working = cap_get_proc()?;
    working.set_flag(CapFlag::Effective, &raise, CapFlagValue::Set)?;
    let ret = cap_set_proc(&working)
        .and_then(|_| lx::setgid(gid).map_err(CapErrno))
        .and_then(|_| lx::setgroups(groups).map_err(CapErrno));
    let olderrno = ret.as_ref().err().copied();
    working.clear_flag(CapFlag::Effective);
    let _ = cap_set_proc(&working);
    match olderrno {
        Some(e) => Err(e),
        None => ret,
    }
}

/// `cap_iab_get_proc()` (CAP-PROC-0020): IAB from the current process
/// (inheritable via capget, bounding/ambient via prctl).
pub fn cap_iab_get_proc() -> CapResult<CapIab> {
    let mut iab = CapIab::new();
    let current = cap_get_proc()?;
    iab.fill(CapIabVector::Inh, &current, CapFlag::Inheritable)?;
    let mut c = cap_max_bits() as i32;
    while c > 0 {
        c -= 1;
        let o = (c as usize) >> 5;
        let mask = 1u32 << (c & 31);
        if cap_get_bound(c) == Ok(0) {
            iab.nb[o] |= mask;
        }
        if cap_get_ambient(c) == Ok(1) {
            iab.a[o] |= mask;
        }
    }
    Ok(iab)
}

/// `cap_iab_set_proc(iab)` (CAP-PROC-0021): apply I to the inheritable set
/// (raising CAP_SETPCAP effective as needed), reset ambient, raise ambient,
/// drop bounding bits, then restore.
pub fn cap_iab_set_proc(iab: &CapIab) -> CapResult<()> {
    let temp = cap_get_proc()?;
    let mut raising = 0u32;
    let mut check_bound = false;
    for i in 0..2 {
        let new_i = iab.i[i];
        let old_ip = temp.inh[i] | temp.perm[i];
        raising |= new_i & !old_ip;
        if iab.nb[i] != 0 {
            check_bound = true;
        }
    }
    if check_bound {
        let mut c = cap_max_bits() as i32;
        while c > 0 {
            c -= 1;
            let o = (c as usize) >> 5;
            let mask = 1u32 << (c & 31);
            if iab.nb[o] & mask != 0 && cap_get_bound(c) == Ok(1) {
                raising = 1;
                check_bound = true;
                break;
            }
        }
    }
    let mut working = temp.dup();
    if raising != 0 {
        working.set_flag(CapFlag::Effective, &[cap::SETPCAP], CapFlagValue::Set)?;
    }
    cap_set_proc(&working)?;
    let mut ret = cap_reset_ambient();
    if ret.is_ok() {
        let mut c = cap_max_bits() as i32;
        while c > 0 {
            c -= 1;
            let o = (c as usize) >> 5;
            let mask = 1u32 << (c & 31);
            if iab.a[o] & mask != 0 {
                ret = cap_set_ambient(c, CapFlagValue::Set);
                if ret.is_err() {
                    break;
                }
            }
            if check_bound && iab.nb[o] & mask != 0 {
                ret = cap_drop_bound(c);
                if ret.is_err() {
                    break;
                }
            }
        }
    }
    let _ = cap_set_proc(&temp);
    ret
}

