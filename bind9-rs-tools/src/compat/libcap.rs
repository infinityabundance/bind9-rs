//! `libcap` conservation module (addendum §27, §37, §38) — a native Rust
//! implementation of the libcap 2.78 C API surface with forensic fidelity.
//!
//! This is NOT a generic capability library.  It conserves libcap's
//! observable behavior as the BIND ecosystem relies on it:
//!
//! - the `cap_t` model: three flag sets (E/P/I) over 64 bits, v3 header,
//!   `rootid` (namespace owner) — `libcap/cap_alloc.c`, `libcap.h`;
//! - the text grammar of `cap_from_text`/`cap_to_text` including the
//!   archived quirks (the `=+`/`=-` ops, the "= "→"name=..." merge, the
//!   `%`/`^`/`!` IAB prefixes, the `all` keyword, numeric capabilities, the
//!   case-insensitive `cap_`-prefixed names) — `libcap/cap_text.c`;
//! - the external (portable) byte format of `cap_copy_ext`/`cap_copy_int`
//!   (magic `90 c2 01 51`) — `libcap/cap_extint.c`;
//! - the VFS file-capability xattr format (revisions 1/2/3, effective-bit
//!   encoding) — `libcap/cap_file.c`;
//! - the process operations (capget/capset, prctl bounding/ambient,
//!   secbits, modes, setuid/setgroups) — `libcap/cap_proc.c`.
//!
//! The kernel-touching calls live behind the audited `platform::linux`
//! boundary (unsafe inventory U-0001..U-0023, §49); everything else is safe
//! Rust.  Courts: `forensics/courts/cap-*` + the C probe
//! `forensics/oracle/probes/probe-libcap.c` (§37).
//!
//! Behavior IDs: CAP-NAME-*, CAP-TEXT-*, CAP-EXT-*, CAP-FLAG-*, CAP-FILE-*,
//! CAP-PROC-*, CAP-IAB-* (atlas: `bind9-rs-tools/forensics/atlas/doxygen/
//! libcap`).

